import assert from 'node:assert/strict';
import { Big } from '@last-orbit/core/big.js';
import { G, recalc } from '@last-orbit/core/game.js';
import { newState, SCHEMA } from '@last-orbit/core/state.js';
import { setBay, equipDroneBay } from '@last-orbit/progression/economy.js';
import { buyMaterialUpgrade } from '@last-orbit/progression/materials.js';
import { projectDef, projectCanBuild, buildProject } from '@last-orbit/progression/projects.js';
import { createWorld, setWaveBase, spawnEnemy } from '@last-orbit/combat/world.js';
import { syncDrones, updateDrones } from '@last-orbit/combat/drones.js';
import { initWorld, startWave } from '@last-orbit/combat/sim.js';
import { parseSave } from '@last-orbit/save/save.js';

G.state = newState();
G.state.run.research.dr_bay = 1;
G.state.unlocks.drones = 1;
recalc();
assert.equal(G.sheet.n('droneBays'), 2);
setBay('attack', 1);
setBay('mining', 1);
assert.deepEqual(G.state.run.drones.bays, ['attack', 'mining']);
setBay('survey', 1);
assert.deepEqual(G.state.run.drones.bays, ['attack', 'survey'], 'specialists replace each other with full bays');
assert.equal(equipDroneBay(0, 'mining'), true);
assert.deepEqual(G.state.run.drones.bays, ['mining', 'attack'], 'loadout fits chosen bay and preserves other craft');

const w = createWorld(); G.world = w; w.wave.state = 'fighting'; w.wave.num = 35; setWaveBase(w, 35, 0);
const enemy = spawnEnemy(w, 'grunt', 0, 95);
syncDrones(w); updateDrones(w, 3.3);
assert.equal(enemy.mined, true, 'mining drone tags an enemy for an extra Ore drop');
equipDroneBay(0, 'survey'); syncDrones(w); updateDrones(w, 3.3);
assert.ok(enemy.droneMarkT > 0 && enemy.droneMarkPower >= 0.08, 'painter tags an enemy for bounded bonus damage');

G.state.materials.smelter = true;
G.state.materials.discoveredOres.iron = true;
G.state.stats.bestWave = 4;
G.state.cur.iron = Big.from(2);
const baseHull = G.sheet.n('hull');
assert.equal(buyMaterialUpgrade('ironFrame'), true);
assert.ok(G.sheet.n('hull') > baseHull, 'refined bars improve persistent ship stats');

const passage = projectDef('passage');
G.state.stats.bestWave = 40; G.state.run.wave = 40; G.state.run.best = 40;
G.state.cur.palladiumOre = Big.from(40);
G.state.cur.iridium = Big.from(1);
G.state.cur.cores = Big.from(1);
assert.equal(projectCanBuild(passage), true);
G.world = initWorld();
G.state.run.wave = 41; startWave(G.world);
assert.equal(G.state.run.wave, 40, 'an unbuilt passage seals the next sector');
G.state.projects.passageBossCleared = true;
assert.equal(buildProject('passage'), true);
assert.equal(G.state.run.wave, 41, 'building after the boss opens the next wave');
assert.equal(G.state.projects.completed.passage > 0, true);
assert.equal(G.state.cur.palladiumOre.toNumber(), 0);

const legacy = newState(); legacy.v = 13; legacy.stats.bestWave = 51;
const migrated = parseSave(JSON.stringify(legacy));
assert.equal(migrated.v, SCHEMA);
assert.ok(migrated.projects.completed.passage, 'existing Graveyard saves keep their route');
console.log('Industry, specialist drones, passage gate and save migration pass.');
